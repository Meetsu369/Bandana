/// BANDANA design system spacing tokens.
///
/// A small, consistent scale based on 4px increments.
/// Larger values added only when genuinely required.
class AppSpacing {
  AppSpacing._();

  /// 4px — Extra small, tight spacing.
  static const double xs = 4.0;

  /// 8px — Small, default compact spacing.
  static const double sm = 8.0;

  /// 16px — Medium, standard spacing.
  static const double md = 16.0;

  /// 24px — Large, section spacing.
  static const double lg = 24.0;

  /// 32px — Extra large, major section spacing.
  static const double xl = 32.0;

  /// 48px — Massive spacing, rarely used.
  static const double xxl = 48.0;

  /// Semantic spacing aliases for common use cases.
  static const double cardPadding = md; // 16
  static const double cardGap = md; // 16
  static const double sectionGap = lg; // 24
  static const double screenPadding = md; // 16
  static const double buttonHeight = 56.0;
  static const double buttonHeightSmall = 44.0;
  static const double iconSizeSmall = 16.0;
  static const double iconSizeMedium = 20.0;
  static const double iconSizeLarge = 24.0;
  static const double iconSizeXLarge = 32.0;
  static const double avatarSizeSmall = 32.0;
  static const double avatarSizeMedium = 40.0;
  static const double avatarSizeLarge = 56.0;
  static const double chipHorizontalPadding = 12.0;
  static const double chipVerticalPadding = 6.0;
  static const double listItemSpacing = 12.0;
  static const double dividerMargin = 16.0;
}